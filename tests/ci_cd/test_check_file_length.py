from __future__ import annotations

from pathlib import Path

import pytest

from tools.ci_cd.check_file_length import (
    MAX_LINES,
    REPO,
    WARN_LINES,
    Exemption,
    Severity,
    count_lines,
    is_exempt,
    scan,
)


def write_lines(path: Path, lines: int) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("x\n" * lines, encoding="utf-8")
    return path


def test_count_lines_counts_physical_lines(tmp_path: Path) -> None:
    assert count_lines(write_lines(tmp_path / "a.py", 3)) == 3
    assert count_lines(write_lines(tmp_path / "b.py", 1)) == 1


def test_count_lines_counts_a_final_line_without_newline(tmp_path: Path) -> None:
    path = tmp_path / "a.py"
    path.write_text("one\ntwo", encoding="utf-8")
    assert count_lines(path) == 2


def test_count_lines_of_an_empty_file_is_zero(tmp_path: Path) -> None:
    path = tmp_path / "a.py"
    path.write_text("", encoding="utf-8")
    assert count_lines(path) == 0


def test_a_module_at_the_warning_limit_is_clean(tmp_path: Path) -> None:
    write_lines(tmp_path / "a.py", WARN_LINES)
    report = scan(tmp_path)
    assert report.checked == 1
    assert report.findings == []


def test_a_module_over_the_warning_limit_warns_without_failing(
    tmp_path: Path,
) -> None:
    write_lines(tmp_path / "a.py", WARN_LINES + 1)
    report = scan(tmp_path)
    assert [finding.severity for finding in report.findings] == [Severity.WARNING]
    assert report.warnings[0].lines == WARN_LINES + 1
    assert report.errors == []


def test_a_module_at_the_ceiling_warns(tmp_path: Path) -> None:
    write_lines(tmp_path / "a.py", MAX_LINES)
    report = scan(tmp_path)
    assert [finding.severity for finding in report.findings] == [Severity.WARNING]


def test_a_module_over_the_ceiling_is_an_error(tmp_path: Path) -> None:
    write_lines(tmp_path / "a.go", MAX_LINES + 1)
    report = scan(tmp_path)
    assert [finding.severity for finding in report.findings] == [Severity.ERROR]
    assert report.errors[0].lines == MAX_LINES + 1


def test_markdown_and_yaml_files_are_scanned(tmp_path: Path) -> None:
    for name in ("doc.md", "data.yaml", "data.yml"):
        write_lines(tmp_path / name, MAX_LINES + 1)
    report = scan(tmp_path)
    assert {finding.path.name for finding in report.errors} == {
        "doc.md",
        "data.yaml",
        "data.yml",
    }


def test_other_suffixes_are_ignored(tmp_path: Path) -> None:
    write_lines(tmp_path / "notes.txt", MAX_LINES + 1)
    write_lines(tmp_path / "data.json", MAX_LINES + 1)
    write_lines(tmp_path / "ok.py", 1)
    report = scan(tmp_path)
    assert report.checked == 1
    assert report.findings == []


def test_skipped_directories_are_not_scanned(tmp_path: Path) -> None:
    write_lines(tmp_path / "data" / "big.py", MAX_LINES + 1)
    write_lines(tmp_path / ".worktrees" / "wt" / "big.py", MAX_LINES + 1)
    write_lines(tmp_path / "__pycache__" / "big.py", MAX_LINES + 1)
    write_lines(tmp_path / ".agents" / "skill" / "huge.md", MAX_LINES + 1)
    report = scan(tmp_path)
    assert report.checked == 0
    assert report.findings == []


def test_findings_are_sorted_by_descending_length(tmp_path: Path) -> None:
    write_lines(tmp_path / "small.py", WARN_LINES + 1)
    write_lines(tmp_path / "large.py", MAX_LINES + 1)
    report = scan(tmp_path)
    assert [finding.path.name for finding in report.findings] == [
        "large.py",
        "small.py",
    ]


def test_an_exemption_removes_a_finding(tmp_path: Path) -> None:
    write_lines(tmp_path / "generated" / "table.py", MAX_LINES + 1)
    exemption = Exemption(path="generated/*.py", reason="generated by a tool")
    report = scan(tmp_path, exemptions=[exemption])
    assert report.findings == []


def test_is_exempt_matches_repository_relative_globs() -> None:
    exemption = Exemption(path="generator/internal/*.go", reason="generated")
    assert is_exempt(Path("generator/internal/table.go"), [exemption])
    assert not is_exempt(Path("generator/main.go"), [exemption])


def test_a_warning_limit_at_or_above_the_ceiling_is_rejected(
    tmp_path: Path,
) -> None:
    with pytest.raises(ValueError):
        scan(tmp_path, warn=MAX_LINES, max_lines=MAX_LINES)


def test_the_repository_is_under_the_ceiling() -> None:
    report = scan(REPO)
    assert report.checked > 0
    assert report.errors == []
